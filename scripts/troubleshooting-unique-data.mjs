function buildSettings(topics) {
  return topics.map((item) => {
    const platform = PLATFORM[item.os];
    const title = item.title;
    const steps = STEPS[item.kind].map((step) => step.replaceAll("{platform}", platform));
    return {
      title,
      slug: "trouble13-unique-" + item.id,
      os: item.os,
      version: VERSION[item.os],
      category: "troubleshoot",
      aliases: [item.title, ...item.keywords.slice(0, 4)],
      path: item.path,
      steps,
      related_slugs: [],
      keywords: [platform, "トラブル解決", ...item.keywords],
      description: `「${title}」の症状が起きたときに、設定・接続・権限・更新の順で原因を切り分ける手順です。`,
      difficulty: item.difficulty || "beginner",
      estimate_minutes: item.estimate_minutes || 8,
      verified_at: VERIFIED_AT,
      review_due_at: REVIEW_DUE_AT,
      source_url: item.source,
      device_scope: `${VERSION[item.os]}を基準にした公式情報ベースの下書き候補です。メーカー・機種・エディション・アプリ版によって項目名が異なる場合があります。`,
      impact: `「${title}」が起きているときの、最初の切り分けと復旧の入口になります。`,
      rollback: "ネットワーク・権限・アカウント・表示設定を変更した場合は、変更前の値を記録してから必要に応じて元に戻します。",
      ...(item.caution ? { caution: item.caution } : {}),
      editor_note: "公式サポートを参照して作成した、1テーマ1ページの重複回避用下書き候補です。公開前に対象機種・OSバージョンで画面と手順を確認してください。",
    };
  });
}

